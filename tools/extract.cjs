// Extracts metamodel, model, views and layout from a .jjodel project export
// into model.js, which the runtime renders.
//
//   node tools/extract.cjs "path/to/Vending Machine.jjodel" [out=model.js]

const fs = require('fs');
const path = require('path');
const { decompressFromUTF16 } = require('./lzstring.cjs');

const [src, out = path.join(__dirname, '..', 'model.js')] = process.argv.slice(2);
if (!src) { console.error('usage: node tools/extract.cjs <project.jjodel> [out]'); process.exit(1); }

const project = JSON.parse(fs.readFileSync(src, 'utf8'));
const state = JSON.parse(decompressFromUTF16(project.state));
const L = Object.fromEntries(Object.entries(state.idlookup).filter(([, v]) => v && typeof v === 'object'));
const get = id => (typeof id === 'string' && L[id]) || {};
const all = cls => Object.values(L).filter(v => v.className === cls);

// ---- metamodel ----
const metamodel = {};
for (const c of all('DClass')) {
  if (c.isPrimitive || c.name === 'EObject') continue;
  metamodel[c.name] = {
    abstract: !!c.abstract,
    extends: (c.extends || []).map(x => get(x).name),
    attributes: Object.fromEntries((c.attributes || []).map(get).map(a =>
      [a.name, { type: get(a.type).name, lower: a.lowerBound, upper: a.upperBound }])),
    references: Object.fromEntries((c.references || []).map(get).map(r =>
      [r.name, { type: get(r.type).name, containment: !!r.containment, lower: r.lowerBound, upper: r.upperBound }])),
  };
}
const classById = Object.fromEntries(all('DClass').map(c => [c.id, c.name]));

// ---- model (M1) ----
const m1 = all('DModel').find(m => !m.isMetamodel);
const objects = all('DObject').map(o => ({
  id: o.id,
  name: o.name,
  class: get(o.instanceof).name,
  // containment: object.father is a DValue whose father is the owning object
  owner: get(get(o.father).father).className === 'DObject' ? get(o.father).father : null,
  ownerFeature: get(o.father).className === 'DValue' ? get(get(o.father).instanceof).name : null,
  features: Object.fromEntries((o.features || []).map(get).map(v =>
    [get(v.instanceof).name, (v.values || []).filter(x => x !== null && x !== undefined)])),
}));

// ---- views (custom viewpoints only; jjodel's built-in Default ones are editor chrome) ----
const viewpoints = all('DViewPoint').filter(vp => !vp.id.startsWith('Pointer_ViewPoint'));
const views = [];
for (const v of all('DViewElement')) {
  const vp = get(v.viewpoint);
  if (!viewpoints.includes(vp)) continue;
  const m = /instanceof\.id\s*=\s*'([^']+)'/.exec(v.oclCondition || '');
  if (!m) continue; // e.g. the "Model Copy" canvas view
  views.push({
    name: v.name,
    viewpoint: vp.name,
    appliesTo: classById[m[1]],
    jsx: v.jsxString || '',
    css: v.css || '',
    usage: v.usageDeclarations || '',
    onDataUpdate: v.onDataUpdate || '',
    events: v.events || {},
    adaptWidth: !!v.adaptWidth,
    adaptHeight: !!v.adaptHeight,
  });
}

// ---- layout of top-level nodes on the model's main graph ----
const mainGraph = (project.graphs || []).map(get).find(g => g.model === m1.id) || all('DGraph').find(g => g.model === m1.id);
const layout = {};
for (const x of Object.values(L)) {
  if (!['DVertex', 'DGraphVertex'].includes(x.className) || x.graph !== mainGraph?.id) continue;
  const o = get(x.model);
  if (o.className !== 'DObject' || layout[o.id] || x.w == null) continue;
  layout[o.id] = { x: x.x, y: x.y, w: x.w, h: x.h };
}

// project metadata (jjodel writes "Created by <name> @<date>" into the description)
const by = /Created by\s+(.+?)\s*@/.exec(project.description || '');
const meta = { author: by ? by[1] : null, created: project.creation || null, modified: project.lastModified || null,
  viewpoints: viewpoints.map(vp => vp.name), jjodelVersion: state.version && state.version.n };

const result = { project: project.name, model: m1.name, meta, metamodel, objects, views, layout };
fs.writeFileSync(out, `// Generated by tools/extract.cjs from "${path.basename(src)}" — do not edit by hand.\nwindow.JJODEL = ${JSON.stringify(result, null, 1)};\n`);
console.log(`wrote ${out}: ${Object.keys(metamodel).length} classes, ${objects.length} objects, ${views.length} views`);
